//! The agent's manual, written once and rendered for each door (Pontis plan §6.1).
//!
//! [`TEMPLATE`] is the source. It names operations as `{capability.id}`, which
//! [`surface::render_text`] turns into each door's own name, so the manual says
//! `get_design` to an MCP host and `design.get` to a Pontis session. Nothing
//! else is substituted, and nothing is cut: the reasoning and the examples
//! that make a rule followable are the manual, and both doors get all of it.
//!
//! - **The MCP door** reads it as `skills/forma/SKILL.md`, which [`mcp_skill`]
//!   generates and `cargo test` writes, so the Claude Code and Codex symlinks
//!   and the `/skill` route keep reading the path they always read.
//!   `scripts/check-bindings.sh` fails when the committed file is not what the
//!   template renders, exactly as it does for the bindings.
//! - **The Pontis door** reads it through `forma.guide` ([`pontis`]): rendered
//!   from the template compiled into the binary, never from a file on disk, so
//!   a deployed server cannot serve a manual that differs from the one CI
//!   tested. Not committed — nothing reads it but the route.
//!
//! **The one difference that is not a name.** Two operations exist only on the
//! MCP door, `forma.status` and `design.renderPreview`, so a manual that teaches
//! them cannot be identical on both. Lines between [`MCP_ONLY_OPEN`] and
//! [`MCP_ONLY_CLOSE`] are kept on the MCP door and dropped on the Pontis one.
//! It runs in that direction only, and a block may name nothing that the
//! Pontis door has — `the_mcp_only_blocks_name_only_what_pontis_lacks` holds
//! both — so it cannot grow into a second manual. Whatever must be true on
//! both doors, including what to do when no render reaches the agent, is
//! written outside the blocks, so the Pontis rendering stands on its own
//! rather than having a hole where the MCP text was.
//!
//! An HTML comment is invisible in rendered Markdown, so a marker that was not
//! stripped would fail silently. It is safe here only because the generated
//! skill is drift-checked: a stripping bug shows up as a diff. Keep it covered.

use std::sync::OnceLock;

use serde::Serialize;
use ts_rs::TS;

use crate::surface::{self, Door};

/// The source of the manual, compiled in.
pub const TEMPLATE: &str = include_str!("../manual/SKILL.md");

/// Where the generated MCP skill lives, from the repository root.
pub const MCP_SKILL_PATH: &str = "skills/forma/SKILL.md";

/// Opens lines only the MCP door keeps. Must be a line of its own.
pub const MCP_ONLY_OPEN: &str = "<!-- mcp-only -->";
/// Closes them.
pub const MCP_ONLY_CLOSE: &str = "<!-- /mcp-only -->";

/// What says, at the top of the generated skill, that it is generated.
const GENERATED_NOTICE: &str = "<!-- This file was generated from crates/agent-catalog/manual/SKILL.md by cargo test. Do not edit this file manually. -->";

/// What `forma.guide` answers.
///
/// Nothing else: no timestamp, because two identical reads must look identical
/// to the invocation ledger's fingerprint, and no capability list, because the
/// session's catalog already answers that and two answers with no precedence
/// are worse than one.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, TS)]
#[ts(export)]
pub struct AgentManual {
    /// A content hash of `text`. It changes exactly when the manual does, and
    /// appears nowhere but here: putting it in the guidance would change the
    /// guidance digest every time the manual changed.
    pub revision: String,
    /// The whole manual as Markdown, rendered for the Pontis door.
    pub text: String,
}

/// The template rendered for `door`.
pub fn render(template: &str, door: Door) -> Result<String, String> {
    let mut kept = String::with_capacity(template.len());
    for line in lines(template)? {
        match line {
            Line::Text(text) => kept.push_str(text),
            Line::McpOnly(text) if door == Door::Mcp => kept.push_str(text),
            Line::McpOnly(_) | Line::Marker => {}
        }
    }
    surface::render_text(&kept, door)
}

/// The text of every MCP-only block, markers excluded.
pub fn mcp_only_blocks(template: &str) -> Result<Vec<String>, String> {
    let mut blocks = Vec::new();
    let mut open = false;
    for line in lines(template)? {
        match line {
            Line::Marker if open => open = false,
            Line::Marker => {
                open = true;
                blocks.push(String::new());
            }
            Line::McpOnly(text) => blocks
                .last_mut()
                .expect("a block line follows an opening marker")
                .push_str(text),
            Line::Text(_) => {}
        }
    }
    Ok(blocks)
}

enum Line<'a> {
    Text(&'a str),
    McpOnly(&'a str),
    Marker,
}

/// Each line of the template, newline included, classified.
fn lines(template: &str) -> Result<Vec<Line<'_>>, String> {
    let mut out = Vec::new();
    let mut open = false;
    for (index, line) in template.split_inclusive('\n').enumerate() {
        let number = index + 1;
        let bare = line.trim_end_matches(['\n', '\r']);
        if bare == MCP_ONLY_OPEN {
            if open {
                return Err(format!("line {number}: an MCP-only block inside another"));
            }
            open = true;
            out.push(Line::Marker);
        } else if bare == MCP_ONLY_CLOSE {
            if !open {
                return Err(format!(
                    "line {number}: closes an MCP-only block never opened"
                ));
            }
            open = false;
            out.push(Line::Marker);
        } else if bare.contains("mcp-only") {
            // A marker anywhere but alone on its line would be left in place,
            // invisibly, on both doors.
            return Err(format!("line {number}: a marker must be a line of its own"));
        } else if open {
            out.push(Line::McpOnly(line));
        } else {
            out.push(Line::Text(line));
        }
    }
    if open {
        return Err("an MCP-only block is never closed".to_string());
    }
    Ok(out)
}

/// `skills/forma/SKILL.md`: the manual for the MCP door, with a line under its
/// front matter saying it is generated — not above it, because a host only
/// reads front matter that opens the file.
///
/// # Panics
///
/// When the template does not render. The template's own tests catch that
/// first.
pub fn mcp_skill() -> String {
    let rendered = render(TEMPLATE, Door::Mcp)
        .unwrap_or_else(|error| panic!("the manual does not render for MCP: {error}"));
    let body = rendered
        .strip_prefix("---\n")
        .expect("the manual opens with front matter");
    let end = body
        .find("\n---\n")
        .expect("the manual's front matter is closed");
    let (front, rest) = body.split_at(end + "\n---\n".len());
    format!("---\n{front}{GENERATED_NOTICE}\n{rest}")
}

/// What `forma.guide` answers: the manual for the Pontis door, and its revision.
///
/// # Panics
///
/// As [`mcp_skill`].
pub fn pontis() -> &'static AgentManual {
    static MANUAL: OnceLock<AgentManual> = OnceLock::new();
    MANUAL.get_or_init(|| {
        let text = render(TEMPLATE, Door::Pontis)
            .unwrap_or_else(|error| panic!("the manual does not render for Pontis: {error}"));
        AgentManual {
            revision: revision(&text),
            text,
        }
    })
}

/// The revision of a rendered manual: its blake3 hash, labelled with the
/// algorithm so a reader never has to guess.
pub fn revision(text: &str) -> String {
    format!("blake3:{}", blake3::hash(text.as_bytes()).to_hex())
}
